import fs from 'fs';
import path from 'path';
import { createTwoFilesPatch } from 'diff';
import { resolveSafePath, getRelativePath } from './pathSafety.js';
import crypto from 'crypto';

export interface PatchProposal {
  patchId: string;
  filePath: string;
  relativeFilePath: string;
  originalContent: string;
  patchedContent: string;
  diff: string;
  addedLinesCount: number;
  removedLinesCount: number;
  targetLineNumber?: number;
  explanation: string;
  checksum: string;
  createdAt: string;
}

export interface PatchApplyResult {
  success: boolean;
  filePath: string;
  patchId: string;
  appliedAt: string;
  backupPath?: string;
  error?: string;
}

// In-memory registry of proposed patches pending user approval
const pendingPatches = new Map<string, PatchProposal>();

/**
 * Creates and registers a patch proposal for user review.
 * Does NOT modify any file.
 */
export function createPatchProposal(
  userPath: string,
  newContentOrSnippet: string,
  workspaceRoot: string,
  options?: {
    isSnippetReplacement?: boolean;
    originalSnippet?: string;
    explanation?: string;
    targetLine?: number;
  }
): PatchProposal {
  const safeAbsPath = resolveSafePath(userPath, workspaceRoot);

  if (!fs.existsSync(safeAbsPath)) {
    throw new Error(`Cannot propose patch: Target file "${userPath}" does not exist.`);
  }

  const originalContent = fs.readFileSync(safeAbsPath, 'utf8');
  let patchedContent = originalContent;

  if (options?.isSnippetReplacement && options.originalSnippet) {
    if (!originalContent.includes(options.originalSnippet)) {
      throw new Error(
        `Original snippet not found in target file "${userPath}". The file may have changed.`
      );
    }
    patchedContent = originalContent.replace(options.originalSnippet, newContentOrSnippet);
  } else {
    patchedContent = newContentOrSnippet;
  }

  const relativePath = getRelativePath(safeAbsPath, workspaceRoot);
  const diff = createTwoFilesPatch(
    `a/${relativePath}`,
    `b/${relativePath}`,
    originalContent,
    patchedContent,
    'original',
    'proposed'
  );

  // Count added/removed lines
  const diffLines = diff.split('\n');
  const addedLinesCount = diffLines.filter(l => l.startsWith('+') && !l.startsWith('+++')).length;
  const removedLinesCount = diffLines.filter(l => l.startsWith('-') && !l.startsWith('---')).length;

  // Generate unique patch ID and checksum of original content for safety
  const checksum = crypto.createHash('sha256').update(originalContent).digest('hex');
  const patchId = `patch_${crypto.randomUUID().slice(0, 8)}`;

  const proposal: PatchProposal = {
    patchId,
    filePath: safeAbsPath,
    relativeFilePath: relativePath,
    originalContent,
    patchedContent,
    diff,
    addedLinesCount,
    removedLinesCount,
    targetLineNumber: options?.targetLine,
    explanation: options?.explanation || 'Bug fix patch generated by Swatex AI',
    checksum,
    createdAt: new Date().toISOString(),
  };

  pendingPatches.set(patchId, proposal);
  return proposal;
}

/**
 * Retrieves a pending patch proposal by ID.
 */
export function getPendingPatch(patchId: string): PatchProposal | undefined {
  return pendingPatches.get(patchId);
}

/**
 * Applies an approved patch after verifying:
 * 1. Safe path constraints
 * 2. Original content checksum matches (file was not tampered with)
 * 3. Creates a .bak backup file
 */
export function applyApprovedPatch(
  patchId: string,
  workspaceRoot: string
): PatchApplyResult {
  const proposal = pendingPatches.get(patchId);

  if (!proposal) {
    throw new Error(
      `Patch with ID "${patchId}" was not found or has already been processed. Re-propose the patch.`
    );
  }

  const safeAbsPath = resolveSafePath(proposal.filePath, workspaceRoot);

  if (!fs.existsSync(safeAbsPath)) {
    throw new Error(`Target file "${proposal.relativeFilePath}" no longer exists.`);
  }

  // Safety check: ensure file hasn't mutated unexpectedly
  const currentContent = fs.readFileSync(safeAbsPath, 'utf8');
  const currentChecksum = crypto.createHash('sha256').update(currentContent).digest('hex');

  if (currentChecksum !== proposal.checksum) {
    throw new Error(
      `Patch safety verification failed: "${proposal.relativeFilePath}" was modified since the patch was proposed. Please review and re-propose.`
    );
  }

  // Create .bak backup
  const backupPath = `${safeAbsPath}.bak`;
  fs.writeFileSync(backupPath, currentContent, 'utf8');

  // Write new content
  fs.writeFileSync(safeAbsPath, proposal.patchedContent, 'utf8');

  // Remove from pending
  pendingPatches.delete(patchId);

  return {
    success: true,
    filePath: proposal.relativeFilePath,
    patchId,
    appliedAt: new Date().toISOString(),
    backupPath,
  };
}

/**
 * Rolls back an applied patch if backup exists.
 */
export function rollbackPatch(userPath: string, workspaceRoot: string): boolean {
  const safeAbsPath = resolveSafePath(userPath, workspaceRoot);
  const backupPath = `${safeAbsPath}.bak`;

  if (fs.existsSync(backupPath)) {
    const backupContent = fs.readFileSync(backupPath, 'utf8');
    fs.writeFileSync(safeAbsPath, backupContent, 'utf8');
    fs.unlinkSync(backupPath);
    return true;
  }

  return false;
}
